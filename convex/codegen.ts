/** Deterministic typed-client codegen (HAR → client), RAE-style, in 6 languages. */

type Endpoint = {
	method: string;
	url: string;
	path: string;
	host: string;
	headers: Record<string, string>;
	query: Record<string, string>;
	bodySample?: string;
	contentType?: string;
	count: number;
};

const LANGS: Record<string, (name: string, eps: Endpoint[]) => string> = {
	python: pyClient,
	typescript: tsClient,
	javascript: jsClient,
	go: goClient,
	curl: curlClient,
	powershell: psClient
};

function pascal(s: string): string {
	return s.replace(/[^a-zA-Z0-9]+(.)?/g, (_, c) => (c ? c.toUpperCase() : "")).replace(/^./, (c) => c.toUpperCase());
}
function snake(s: string): string {
	return s.replace(/[^a-zA-Z0-9]+/g, "_").replace(/^_+|_+$/g, "").toLowerCase();
}
function camel(s: string): string {
	const p = pascal(s);
	return p.charAt(0).toLowerCase() + p.slice(1);
}

function pyClient(name: string, eps: Endpoint[]): string {
	const methods = eps
		.map((e) => {
			const fn = snake(`${e.method.toLowerCase()}_${e.path.replace(/[^a-zA-Z0-9]+/g, "_")}`);
			const params: string[] = [`self`];
			const pathParams = [...e.path.matchAll(/\{(\w+)\}/g)].map((m) => m[1]);
			for (const p of pathParams) params.push(`${p}: str`);
			const hasBody = e.bodySample && !["GET", "HEAD"].includes(e.method);
			if (hasBody) params.push(`payload: dict | None = None`);
			let body = "";
			if (hasBody) {
				body = `\n        json=payload,`;
			}
			return `    def ${fn}(${params.join(", ")}) -> dict:
        """${e.method} ${e.path} — captured from ${e.host} (${e.count} sample${e.count === 1 ? "" : "s"})."""
        url = f"${e.url}"${pathParams.length ? `.replace(${pathParams.map((p) => `"${e.url.replace(`{${p}}`, `{${p}}`)}`).join(", ")})` : ""}
        resp = requests.request(
            "${e.method}",
            url,${body}
            headers=BASE_HEADERS,
            timeout=30,
        )
        resp.raise_for_status()
        return resp.json()`;
		})
		.join("\n\n");
	return `"""${name} API client — generated by Guru AI Reverse API Lab.

Endpoints were reverse engineered from a network capture of ${eps[0]?.host ?? "the target site"}.
Review the header list below; remove anything that is not needed.
"""
import requests

BASE_URL = "${eps[0]?.host ? `https://${eps[0].host}` : "https://example.com"}"
BASE_HEADERS = {
${Object.entries(eps[0]?.headers ?? {})
	.map(([k, v]) => `    "${k}": "${v.replace(/"/g, '\\"')}",`)
	.join("\n") || '    "User-Agent": "guru-ai/1.0",'}
}


class ${pascal(name)}Client:
${methods}
`;
}

function tsClient(name: string, eps: Endpoint[]): string {
	const methods = eps
		.map((e) => {
			const fn = camel(`${e.method.toLowerCase()} ${e.path.replace(/[^a-zA-Z0-9]+/g, " ")}`);
			const hasBody = e.bodySample && !["GET", "HEAD"].includes(e.method);
			const params = [`opts: RequestInit = {}`];
			return `  /** ${e.method} ${e.path} — ${e.count} capture sample${e.count === 1 ? "" : "s"} */
  async ${fn}(${params.join(", ")}): Promise<unknown> {
    const res = await fetch(\`${e.url}\`, {
      method: "${e.method}",${hasBody ? `\n      body: opts.body ?? ${JSON.stringify(safeJson(e.bodySample))},` : ""}
      headers: { ...BASE_HEADERS, ...opts.headers },
      ...opts,
    });
    if (!res.ok) throw new Error(\`${e.method} ${e.path} failed: \${res.status}\`);
    return res.json();
  }`;
		})
		.join("\n\n");
	return `// ${name} API client — generated by Guru AI Reverse API Lab
// Reverse engineered from a network capture of ${eps[0]?.host ?? "the target site"}.

export const BASE_URL = "${eps[0]?.host ? `https://${eps[0].host}` : "https://example.com"}";

export const BASE_HEADERS: Record<string, string> = {
${Object.entries(eps[0]?.headers ?? {})
	.map(([k, v]) => `  "${k}": "${v.replace(/"/g, '\\"')}",`)
	.join("\n") || `  "User-Agent": "guru-ai/1.0",`}
};

export class ${pascal(name)}Client {
${methods}
}
`;
}

function jsClient(name: string, eps: Endpoint[]): string {
	const t = tsClient(name, eps);
	return t.replace(/: Promise<unknown>/g, "").replace(/: Record<string, string>/g, "").replace(/^export /gm, "");
}

function safeJson(sample?: string): string {
	if (!sample) return "{}";
	try {
		return JSON.stringify(JSON.parse(sample));
	} catch {
		return JSON.stringify(sample);
	}
}

function goClient(name: string, eps: Endpoint[]): string {
	const methods = eps
		.map((e) => {
			const fn = pascal(`${e.method.toLowerCase()}_${e.path.replace(/[^a-zA-Z0-9]+/g, "_")}`);
			const hasBody = e.bodySample && !["GET", "HEAD"].includes(e.method);
			return `// ${e.method} ${e.path}
func (c *${pascal(name)}Client) ${fn}(ctx context.Context${hasBody ? ", payload []byte" : ""}) ([]byte, error) {
	req, err := http.NewRequestWithContext(ctx, "${e.method}", "${e.url}"${hasBody ? `, bytes.NewReader(payload)` : ""})
	if err != nil {
		return nil, err
	}
	for k, v := range BaseHeaders {
		req.Header.Set(k, v)
	}
	resp, err := c.HTTP.Do(req)
	if err != nil {
		return nil, err
	}
	defer resp.Body.Close()
	return io.ReadAll(resp.Body)
}`;
		})
		.join("\n\n");
	return `// ${name} API client — generated by Guru AI Reverse API Lab
package ${snake(name).replace(/_/g, "")}

import (
	"bytes"
	"context"
	"io"
	"net/http"
)

var BaseHeaders = map[string]string{
${Object.entries(eps[0]?.headers ?? {})
	.map(([k, v]) => `	"${k}": "${v.replace(/"/g, '\\"')}",`)
	.join("\n") || `"User-Agent": "guru-ai/1.0",`}
}

type ${pascal(name)}Client struct {
	HTTP *http.Client
}

func New${pascal(name)}Client() *${pascal(name)}Client {
	return &${pascal(name)}Client{HTTP: http.DefaultClient}
}

${methods}
`;
}

function curlClient(_name: string, eps: Endpoint[]): string {
	return eps
		.map((e) => {
			const hasBody = e.bodySample && !["GET", "HEAD"].includes(e.method);
			return `# ${e.method} ${e.path} (${e.count} sample${e.count === 1 ? "" : "s"})\ncurl -X ${e.method} "${e.url}" \\\n${Object.entries(e.headers)
				.map(([k, v]) => `  -H "${k}: ${v.replace(/"/g, '\\"')}" \\\n`)
				.join("")}${hasBody ? `  -d '${safeJson(e.bodySample).replace(/'/g, `'\\''`)}'` : ""}`;
		})
		.join("\n\n");
}

function psClient(name: string, eps: Endpoint[]): string {
	const methods = eps
		.map((e) => {
			const fn = pascal(`${e.method.toLowerCase()}_${e.path.replace(/[^a-zA-Z0-9]+/g, "_")}`);
			const hasBody = e.bodySample && !["GET", "HEAD"].includes(e.method);
			return `function Invoke-${fn} {
    param(${hasBody ? "$Payload" : ""})
    Invoke-RestMethod -Method ${e.method} -Uri "${e.url}" -Headers $BaseHeaders${hasBody ? " -Body $Payload -ContentType 'application/json'" : ""}
}`;
		})
		.join("\n\n");
	return `# ${name} API client — generated by Guru AI Reverse API Lab
$BaseHeaders = {
${Object.entries(eps[0]?.headers ?? {})
	.map(([k, v]) => `    "${k}" = "${v.replace(/"/g, '`"')}"`)
	.join("\n") || `'User-Agent' = 'guru-ai/1.0'`}
}

${methods}
`;
}

export const generateClient = action({
	args: { sessionId: v.id("harSessions"), workspaceId: v.id("workspaces"), language: v.string() },
	handler: async (ctx, { sessionId, workspaceId, language }) => {
		const session = await ctx.runQuery(internal.harInternal.getSessionInternal, { id: sessionId });
		if (!session) throw new Error("Capture session not found.");
		const eps = (session.endpoints as Endpoint[]) ?? [];
		const fn = LANGS[language];
		if (!fn) throw new Error(`Unsupported language "${language}". Supported: ${Object.keys(LANGS).join(", ")}.`);
		const name = snake(session.name).replace(/_api$/, "").replace(/_api$/, "");
		const code = fn(name, eps);
		const id = await ctx.runMutation(internal.harInternal.insertClient, { sessionId, workspaceId, language, code, generatedBy: "template" });
		return { clientId: id, bytes: code.length };
	}
});
